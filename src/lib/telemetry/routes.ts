const matchers = pageRoutes.map((template) => ({
  template,
  pattern: new RegExp(
    "^" +
      template
        .split("/")
        .map((part) => (part.startsWith("[") ? "[^/]+" : part))
        .join("/") +
      "/?$",
  ),
}));

export function pageTemplate(pathname: string): string | null {
  if (!pathname.startsWith("/") || /[?#]/.test(pathname)) return null;
  return (
    matchers.find(({ pattern }) => pattern.test(pathname))?.template ?? null
  );
}
