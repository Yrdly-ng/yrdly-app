export function validatePersonas(entries) {
  if (entries.length !== 50)
    throw new Error("Exactly 50 personas are required");
  for (const key of ["slot", "name", "username"]) {
    if (new Set(entries.map((p) => p[key])).size !== 50)
      throw new Error(`Duplicate persona ${key}`);
  }
  for (const p of entries) {
    if (
      !Number.isInteger(p.slot) ||
      p.slot < 1 ||
      p.slot > 50 ||
      !/fictional.*YRDLY/i.test(p.bio) ||
      !p.writing_style ||
      p.interests.length < 3 ||
      p.posting_preferences.formats.length < 2
    ) {
      throw new Error(`Invalid persona slot ${p.slot}`);
    }
  }
  return true;
}
